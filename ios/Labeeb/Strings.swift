import Foundation

/// Looks up interface text in the language chosen inside the app, which can differ from the phone's language.
func t(_ key: String) -> String {
    guard let pair = Strings.table[key] else { return key }
    return AppSettings.shared.isArabic ? pair.0 : pair.1
}

func t(_ key: String, _ value: String) -> String {
    t(key).replacingOccurrences(of: "%@", with: value)
}

/// A number in the digits of the interface language.
func num(_ n: Int) -> String {
    let f = NumberFormatter()
    f.locale = AppSettings.shared.locale
    return f.string(from: NSNumber(value: n)) ?? String(n)
}

